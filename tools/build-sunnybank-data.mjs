// Build compact address + parcel data for the mobile prototype.
// Source: QLD Spatial "LandParcelPropertyFramework" MapServer
//   layer 0 = Addresses, layer 4 = Cadastral parcels (Lot Type Parcel only)
// Licence: © State of Queensland (Department of Resources), CC BY 4.0
//
// Usage: node tools/build-sunnybank-data.mjs <raw-dir> <out.js>
//   <raw-dir> contains addr_*.json and parcel_*.json (GeoJSON pages from the query API)
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const [rawDir, outFile] = process.argv.slice(2);
if (!rawDir || !outFile) { console.error('usage: build-sunnybank-data.mjs <raw-dir> <out.js>'); process.exit(1); }

const pages = prefix => readdirSync(rawDir).filter(f => f.startsWith(prefix + '_') && f.endsWith('.json'))
  .flatMap(f => JSON.parse(readFileSync(join(rawDir, f), 'utf8')).features || []);

// Coordinates are stored as integer micro-degree offsets from an origin to keep the file small.
const O = [153.0, -27.5];
const enc = ([lng, lat]) => [Math.round((lng - O[0]) * 1e6), Math.round((lat - O[1]) * 1e6)];

// ---- parcels ----
const parcels = new Map();
for (const f of pages('parcel')) {
  const p = f.properties, g = f.geometry;
  if (!g || !p.lotplan || parcels.has(p.lotplan)) continue;
  const rings = g.type === 'Polygon' ? [g.coordinates[0]] : g.type === 'MultiPolygon' ? g.coordinates.map(c => c[0]) : [];
  if (!rings.length) continue;
  parcels.set(p.lotplan, { lp: p.lotplan, area: Math.round(p.lot_area || 0), r: rings.map(r => r.map(enc).flat()) });
}

// ---- addresses ----
const TYPE = { Street: 'St', Road: 'Rd', Avenue: 'Ave', Court: 'Ct', Place: 'Pl', Drive: 'Dr', Crescent: 'Cres', Close: 'Cl', Parade: 'Pde', Terrace: 'Tce', Lane: 'Ln', Way: 'Way', Circuit: 'Cct', Boulevard: 'Blvd', Highway: 'Hwy', Grove: 'Gr', Square: 'Sq' };
const addrs = [], seen = new Set();
for (const f of pages('addr')) {
  const p = f.properties;
  if (!p.street_number || !p.street_name || p.latitude == null) continue;
  if (p.address_pid && seen.has(p.address_pid)) continue;
  seen.add(p.address_pid);
  const street = `${p.street_name} ${TYPE[p.street_type] || p.street_type || ''}`.trim();
  const [x, y] = enc([p.longitude, p.latitude]);
  addrs.push([p.unit_number ? String(p.unit_number) : '', String(p.street_number), street, p.locality, p.lotplan || '', x, y, p.address_pid || 0]);
}
addrs.sort((a, b) => a[2].localeCompare(b[2]) || parseInt(a[1]) - parseInt(b[1]) || a[1].localeCompare(b[1]) || (+a[0] || 0) - (+b[0] || 0));

// Keep only parcels that carry at least one address (drops parks, drainage reserves, etc.).
const used = new Set(addrs.map(a => a[4]));
const parcelList = [...parcels.values()].filter(p => used.has(p.lp));

const data = {
  source: 'QLD Spatial · LandParcelPropertyFramework (Addresses + Cadastral parcels) · © State of Queensland, CC BY 4.0',
  built: new Date().toISOString().slice(0, 10),
  origin: O,
  // [unit, number, street, suburb, lotplan, x, y, address_pid]
  addresses: addrs,
  // { lp, area, r: [[x0,y0,x1,y1,...], ...] }
  parcels: parcelList,
};
writeFileSync(outFile, `// Generated by tools/build-sunnybank-data.mjs — do not edit by hand.\nwindow.SUNNYBANK = ${JSON.stringify(data)};\n`);
const missing = addrs.filter(a => !parcels.has(a[4])).length;
console.log(`addresses ${addrs.length} · parcels ${parcelList.length}/${parcels.size} · addresses without parcel ${missing} · ${(JSON.stringify(data).length / 1024).toFixed(0)} KB`);
